def _entry(node, names, department, path) -> dict:
    """Build one flat category row from an inventory node."""
    return {
        "category": path,
        "department": department or node["name"],
        "subcategory": " > ".join(names[1:]) or node["name"],
        "name": node["name"],
        "cgid": node["cgid"],
        "site_url": node["url"],
        "url": BELK_API_BASE + "/category/" + path + "?v2=true",
        "path": path,
    }


def _flatten() -> list:
    """Flatten the nested inventory into one entry per unique browse path.

    Nodes flagged ``search`` never become categories but are still traversed, so the real
    browse categories underneath a "Shop All..." shortcut keep their department context.
    When one path is linked from several places the shallowest occurrence wins.
    """
    flat: list = []
    seen: dict = {}

    def walk(nodes, department=None, trail=None, level=1):
        for node in nodes:
            names = (trail or []) + [node["name"]]
            path = node.get("path")
            if path:
                known = seen.get(path)
                if known is None:
                    seen[path] = (level, len(flat))
                    flat.append(_entry(node, names, department, path))
                elif level < known[0]:
                    seen[path] = (level, known[1])
                    flat[known[1]] = _entry(node, names, department, path)
            walk(node.get("subcategories") or [], department or node["name"], names, level + 1)

    walk(BELK_CATEGORY_INVENTORY)
    return flat


BELK_CATEGORIES = _flatten()
