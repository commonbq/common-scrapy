def _slug(value: str) -> str:
    expanded = value.lower().replace("&", "and").replace("+", "plus")
    return re.sub(r"[^a-z0-9]+", "-", expanded).strip("-")


def flatten_categories() -> list[dict[str, str]]:
    """Flatten navigation labels and deduplicate identical category IDs."""
    categories = []
    seen = set()
    aliases = set()
    for department, entries in ASOS_CATEGORY_INVENTORY.items():
        for label, url in entries.items():
            cid = parse_qs(urlparse(url).query).get("cid", [None])[0]
            if not cid or cid in seen:
                continue
            seen.add(cid)
            alias = f"{department}-{_slug(label)}"
            if alias in aliases:
                alias = f"{alias}-{cid}"
            aliases.add(alias)
            categories.append({
                "category": alias,
                "subcategory": label,
                "department": department,
                "cid": cid,
                "url": url,
            })
    return categories


ASOS_CATEGORIES = flatten_categories()

